/**
 * v0.6.0: the ready-made presentation of a topic (GET /topics/:key/deck).
 * Built from the published package only — no teacher input, no LLM — so it
 * is deterministic and can be cached per package hash × language × format.
 *
 * Order follows the lesson: title → goals (+ textbook place) → samples as 3D
 * images → the tour steps (teacher notes in the speaker notes) → key
 * concepts → processes → examples → questions (answers in the notes) →
 * sources. Sample thumbnails are WebP; they are converted to PNG because
 * pdfkit cannot embed WebP and older PowerPoint cannot show it.
 */
import sharp from 'sharp';
import { t, topicConcepts, type ContentPackage, type Item, type Lang, type Textbook, placesOfTopic } from '@bilig/content-model';
import type { Slide } from '@bilig/content-model/api';
import { newId } from '../ids.js';
import { texToText } from '../domain/tex.js';
import type { DeckImage, DeckInput } from '../export/deck-types.js';
import type { AssetStore } from './assets.js';

