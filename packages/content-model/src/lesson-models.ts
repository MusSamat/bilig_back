/** The model by id (the default one for an unknown id). */
export const lessonModel = (id: string | null | undefined): LessonModel =>
  LESSON_MODELS.find((m) => m.id === id) ??
  LESSON_MODELS.find((m) => m.id === DEFAULT_LESSON_MODEL)!;

/** Key of a stage's content in a lesson: `<modelId>:<stageKey>` (switching models keeps each model's text). */
export const stageContentKey = (modelId: LessonModelId, stageKey: string) =>
  `${modelId}:${stageKey}`;
