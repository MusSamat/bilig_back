/**
 * v0.10.0: the four lesson models of the teacher cabinet (5E, 3C + 1E, PEM·А, PEM·Б). A lesson plan is
 * built from a model's stages; the cabinet's guide shows the rest. Texts are in Kyrgyz — the language of
 * the official «Сабактын планы» form. Pure data: the server fills the .docx from it, the client draws it.
 */

export const LESSON_MODEL_IDS = ['5e', '3c1e', 'pemA', 'pemB'] as const;
export type LessonModelId = (typeof LESSON_MODEL_IDS)[number];

/** Icon key of a stage; the client maps it to a glyph. */
export type LessonStageIcon =
  | 'engage'
  | 'explore'
  | 'explain'
  | 'elaborate'
  | 'evaluate'
  | 'connect'
  | 'construct'
  | 'consolidate'
  | 'extend'
  | 'predict'
  | 'modify'
  | 'present'
  | 'mastery';

export interface LessonModelStage {
  /** Stable key, unique within the model (lesson content is stored per `<modelId>:<key>`). */
  key: string;
  /** International name («Engage», «Catch / Connect»). */
  code: string;
  /** Kyrgyz name («Кызыктыруу / Тартуу»). */
  title: string;
  icon: LessonStageIcon;
  /** Suggested minutes of a 45-minute lesson. */
  minutes: number;
  /** An optional stage (dashed in the guide). */
  optional?: boolean;
  /** The stage runs through the whole lesson (5E Evaluate). */
  spansLesson?: boolean;
  text: string;
  /** What the teacher does — also the hint of an empty «Мугалим» field. */
  teacher: string[];
  /** What the pupils do — the hint of an empty «Окуучулар» field. */
  pupil: string;
  /** A worked example («Кан жана анын курамы», biology, 8th grade). */
  example: string;
}

export interface LessonModel {
  id: LessonModelId;
  short: string;
  name: string;
  full: string;
  /** Brand colour of the model (hex). */
  color: string;
  basis: string;
  idea: string;
  tagline: string;
  /** Who leads the lesson. */
  lead: string;
  /** What it suits best. */
  best: string;
  /** A note about a stage that spans the lesson. */
  spanText?: string;
  /** A note about the model's loop (PEM·А: Modify → Predict). */
  loopText?: string;
  /** The other model of the same name (PEM·А ↔ PEM·Б). */
  pairedWith?: LessonModelId;
  stages: LessonModelStage[];
  /** How to prepare a lesson with the model. */
  how: string[];
  features: string[];
  when: string[];
  notFor: string[];
  /** How it differs from the other models. */
  diff: string;
}

